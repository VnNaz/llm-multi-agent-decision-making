"""Отдельное построение графиков и таблиц RPS по сохранённым CSV."""
import argparse
import csv
from collections import defaultdict
from pathlib import Path
from statistics import mean

from rps.game import FAMILY_ORDER
from rps.metrics import summarize


def main():
    parser = argparse.ArgumentParser(description="Plot Fan-style RPS payoff curves")
    parser.add_argument("--input", type=Path, nargs="+", required=True,
                        help="One or more rounds.csv generated by fan_rps.py")
    parser.add_argument("--out", type=Path, default=None)
    args = parser.parse_args()
    try:
        import matplotlib.pyplot as plt
    except ImportError as exc:
        raise SystemExit("Install matplotlib: python -m pip install matplotlib") from exc
    args.out = args.out or (args.input[0].parent if args.input[0].is_file() else args.input[0]) / "figures"
    args.out.mkdir(parents=True, exist_ok=True)
    inputs = [path / "rounds.csv" if path.is_dir() else path for path in args.input]
    by_family_round, by_scenario = summarize(inputs)
    with (args.out / "average_payoff_by_round.csv").open("w", newline="", encoding="utf-8") as fh:
        writer = csv.writer(fh)
        writer.writerow(["player", "family", "round", "n", "average_payoff"])
        for (label, family, rnd), scores in sorted(by_family_round.items()):
            writer.writerow([label, family, rnd, len(scores), f"{mean(scores):.4f}"])
    with (args.out / "average_payoff_by_scenario.csv").open("w", newline="", encoding="utf-8") as fh:
        writer = csv.writer(fh)
        writer.writerow(["player", "scenario", "family", "n", "average_payoff"])
        for (label, scenario, family), scores in sorted(by_scenario.items()):
            writer.writerow([label, scenario, family, len(scores), f"{mean(scores):.4f}"])
    fig, axs = plt.subplots(2, 3, figsize=(13, 7), sharex=True, sharey=True)
    labels = sorted({x[0] for x in by_family_round}, key=lambda x: (x != "Random", x))
    for ax, family in zip(axs.flat, FAMILY_ORDER):
        for label in labels:
            xs = sorted(rnd for lab, fam, rnd in by_family_round if lab == label and fam == family)
            if xs:
                ys = [mean(by_family_round[(label, family, rnd)]) for rnd in xs]
                ax.plot(xs, ys, marker="o", label=label)
        ax.set_title(family)
        ax.set_xlim(left=1)
        ax.set_ylim(0, 2)
        ax.set_xlabel("Round")
        ax.set_ylabel("Average payoff")
        ax.grid(alpha=0.2)
    handles, legend_labels = axs.flat[0].get_legend_handles_labels()
    if handles:
        fig.legend(handles, legend_labels, loc="upper center", ncol=len(handles))
    fig.suptitle("Fan et al. (2024) RPS adaptation — average payoff by round", y=1.01)
    fig.tight_layout(rect=(0, 0, 1, 0.95))
    path = args.out / "figure3_style.png"
    fig.savefig(path, dpi=160, bbox_inches="tight")
    plt.close(fig)
    print("Summary:", args.out / "average_payoff_by_round.csv")
    print("Summary:", args.out / "average_payoff_by_scenario.csv")
    print("Chart:  ", path)
    print("Note: plotted data come from YOUR runs, not Fan's published series.")


if __name__ == "__main__":
    main()
